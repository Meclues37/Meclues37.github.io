const normalizedTranslations = new Map(
  Object.entries(translations).map(([english, chinese]) => [
    normalize(english),
    chinese
  ])
);

const originalText = new WeakMap();
const originalAttributes = new WeakMap();

function normalize(value) {
  return value
    .replace(/鈥檚/g, "s")
    .replace(/鈥檝e/g, "ve")
    .replace(/鈥檓/g, "m")
    .replace(/鈥檛/g, "t")
    .replace(/鈥檒l/g, "ll")
    .replace(/鈥攚/g, "w")
    .replace(/鈥攁/g, "a")
    .replace(/鈥攂/g, "b")
    .replace(/鈥攑/g, "p")
    .replace(/鈥攕/g, "s")
    .replace(/鈥[?？]?/g, " ")
    .replace(/[\u2018\u2019']/g, "")
    .replace(/[\u201c\u201d"]/g, "")
    .replace(/[?？\ufffd]+/g, "")
    .replace(/[\u2013\u2014]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function translated(value) {
  return normalizedTranslations.get(normalize(value));
}

function preserveSpacing(original, replacement) {
  const leading = original.match(/^\s*/)?.[0] || "";
  const trailing = original.match(/\s*$/)?.[0] || "";
  return `${leading}${replacement}${trailing}`;
}

function collectTranslatableContent() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;

  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (!parent || ["SCRIPT", "STYLE", "NOSCRIPT"].includes(parent.tagName)) {
      continue;
    }

    if (translated(node.nodeValue || "")) {
      originalText.set(node, node.nodeValue);
    }
  }

  document.querySelectorAll("[alt], [title], [aria-label], [placeholder]").forEach(element => {
    const values = {};
    ["alt", "title", "aria-label", "placeholder"].forEach(attribute => {
      const value = element.getAttribute(attribute);
      if (value && translated(value)) {
        values[attribute] = value;
      }
    });
    if (Object.keys(values).length) {
      originalAttributes.set(element, values);
    }
  });
}


function translateTravelNoteBlocks(useChinese) {
  document.querySelectorAll(".travel-notes p, .travel-notes h2, .trail-awards p").forEach(element => {
    if (!element.dataset.englishText) {
      element.dataset.englishText = normalize(element.textContent || "");
    }
    const english = element.dataset.englishText;
    const chinese = translated(english);
    if (chinese) {
      element.textContent = useChinese ? chinese : english;
    }
  });
}

function applyLanguage(language) {
  const useChinese = language === "zh";

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!originalText.has(node)) continue;
    const english = originalText.get(node);
    node.nodeValue = useChinese
      ? preserveSpacing(english, translated(english))
      : english;
  }

  document.querySelectorAll("[alt], [title], [aria-label], [placeholder]").forEach(element => {
    const originals = originalAttributes.get(element);
    if (!originals) return;
    Object.entries(originals).forEach(([attribute, english]) => {
      element.setAttribute(
        attribute,
        useChinese ? translated(english) : english
      );
    });
  });

  const englishTitle = document.documentElement.dataset.englishTitle;
  document.title = useChinese
    ? translated(englishTitle) || englishTitle
    : englishTitle;

  document.documentElement.lang = useChinese ? "zh-CN" : "en";
  document.documentElement.dataset.language = language;

  translateTravelNoteBlocks(useChinese);

  const switcher = document.querySelector(".language-switcher");
  if (switcher) {
    switcher.querySelector(".language-switcher__label").textContent =
      useChinese ? "EN" : "中文";
    switcher.setAttribute(
      "aria-label",
      useChinese ? "Switch to English" : "切换为中文"
    );
    switcher.title = useChinese ? "Switch to English" : "切换为中文";
  }
}

function createSwitcher() {
  const button = document.createElement("button");
  button.type = "button";
  button.className = "language-switcher";
  button.innerHTML = `
    <span class="language-switcher__icon" aria-hidden="true">🌐</span>
    <span class="language-switcher__label">中文</span>
  `;
  button.addEventListener("click", () => {
    const next =
      document.documentElement.dataset.language === "zh" ? "en" : "zh";
    localStorage.setItem("portfolioLanguage", next);
    applyLanguage(next);
  });
  document.body.appendChild(button);
}

